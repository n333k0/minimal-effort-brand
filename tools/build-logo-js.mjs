// Writes assets/js/logos.js: every logo in assets/logo as a currentColor SVG string plus its aspect ratio,
// and the Minimal Effort icon set (drawn as extensions of the ME mark: filled rectangles only, bar = 16 on a 100 grid,
// the same bar-to-height ratio as the ME mark's legs). Run: node tools/build-logo-js.mjs
import fs from 'fs';
import path from 'path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const L = {
  'me-mark': 'ME mark', 'mnml-effrt': 'MNML EFFRT', 'mnml-effrt-square': 'MNML ■ EFFRT', 'wordmark': 'MINIMAL EFFORT', 'lockup': 'Lockup',
  'the-maze': 'THE MAZE', 'origin-mark': 'ORIGIN mark', 'origin': 'ORIGIN', 'sbcltr': 'SBCLTR', 'lee-burridge': 'Lee Burridge',
};
const LOGO = {}, META = {};
for (const [k, label] of Object.entries(L)) {
  const s = fs.readFileSync(path.join(ROOT, 'assets/logo', k + '.svg'), 'utf8').replace(/<title>.*?<\/title>/, '').trim();
  const [, , w, h] = s.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  LOGO[k] = s; META[k] = { label, aspect: +(w / h).toFixed(4) };
}
// icons: [x, y, w, h] rectangles on a 100 x 100 grid, bar = 16
const R = (...r) => r;
const frame = (x, y, w, h, t = 16) => [R(x, y, w, t), R(x, y + h - t, w, t), R(x, y, t, h), R(x + w - t, y, t, h)];
const ICONS = {
  float:    [R(0, 18, 64, 16), R(36, 42, 64, 16), R(0, 66, 64, 16)],
  artists:  [R(36, 0, 28, 28), R(10, 38, 80, 16), R(10, 38, 16, 62), R(74, 38, 16, 62)],
  gallery:  [...frame(0, 8, 100, 84), R(28, 44, 26, 26)],
  tickets:  [R(0, 22, 56, 56), R(68, 22, 32, 56)],
  clinic:   [...frame(0, 0, 100, 100), R(42, 26, 16, 48), R(26, 42, 48, 16)],
  calendar: [...frame(0, 12, 100, 88), R(0, 12, 100, 30), R(20, 0, 16, 20), R(64, 0, 16, 20)],
  pin:      [...frame(18, 0, 64, 64), R(42, 64, 16, 36)],
  clock:    [...frame(0, 0, 100, 100), R(42, 18, 16, 40), R(42, 42, 34, 16)],
  music:    [R(14, 0, 72, 16), R(14, 0, 16, 72), R(70, 0, 16, 72), R(0, 70, 30, 30), R(56, 70, 30, 30)],
  info:     [R(42, 0, 16, 16), R(42, 30, 16, 70)],
  arrow:    [R(0, 42, 66, 16), R(66, 18, 16, 64), R(82, 34, 18, 32)],
  plus:     [R(42, 10, 16, 80), R(10, 42, 80, 16)],
  play:     [R(14, 6, 18, 88), R(32, 22, 18, 56), R(50, 36, 18, 28)],
  link:     [...frame(0, 22, 58, 56), ...frame(42, 22, 58, 56)],
  star:     [R(42, 0, 16, 100), R(0, 42, 100, 16), R(30, 30, 40, 40)],
  waitlist: [...frame(0, 0, 100, 100), R(28, 42, 44, 16)],
};
const icon = Object.fromEntries(Object.entries(ICONS).map(([k, rs]) => [k, rs.map(([x, y, w, h]) => `<rect x="${x}" y="${y}" width="${w}" height="${h}"/>`).join('')]));
fs.writeFileSync(path.join(ROOT, 'assets/js/logos.js'), `// generated by tools/build-logo-js.mjs — do not edit by hand\nexport const LOGO = ${JSON.stringify(LOGO)};\nexport const LOGO_META = ${JSON.stringify(META, null, 0)};\nexport const ICON_RECTS = ${JSON.stringify(icon)};\n`);
console.log(Object.keys(LOGO).length, 'logos,', Object.keys(icon).length, 'icons');
